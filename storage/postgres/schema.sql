-- =============================================================================
-- IMMUTABILITY TRIGGER FOR LDU-W
-- =============================================================================

CREATE OR REPLACE FUNCTION ldu_w_enforce_immutability()
RETURNS TRIGGER AS $$
BEGIN
    -- Block changes to IMMUTABLE columns (core definition data)
    
    -- Check if term changed (IMMUTABLE)
    IF NEW.term IS DISTINCT FROM OLD.term THEN
        RAISE EXCEPTION 'LDU-W term is immutable (definition %)', OLD.id;
    END IF;
    
    -- Check if claim changed (IMMUTABLE - the workable definition itself)
    IF NEW.claim IS DISTINCT FROM OLD.claim THEN
        RAISE EXCEPTION 'LDU-W claim is immutable (definition %)', OLD.id;
    END IF;
    
    -- Check if source_ldu_t_ids changed (IMMUTABLE - lineage cannot change)
    IF NEW.source_ldu_t_ids IS DISTINCT FROM OLD.source_ldu_t_ids THEN
        RAISE EXCEPTION 'LDU-W source lineage is immutable (definition %)', OLD.id;
    END IF;
    
    -- Check if gdu_shape changed (IMMUTABLE)
    IF NEW.gdu_shape IS DISTINCT FROM OLD.gdu_shape THEN
        RAISE EXCEPTION 'LDU-W GDU shape is immutable (definition %)', OLD.id;
    END IF;
    
    -- Check if any scope field changed (IMMUTABLE)
    IF NEW.scope_domain IS DISTINCT FROM OLD.scope_domain THEN
        RAISE EXCEPTION 'LDU-W scope cannot change (definition %)', OLD.id;
    END IF;
    IF NEW.scope_culture IS DISTINCT FROM OLD.scope_culture THEN
        RAISE EXCEPTION 'LDU-W scope cannot change (definition %)', OLD.id;
    END IF;
    IF NEW.scope_community IS DISTINCT FROM OLD.scope_community THEN
        RAISE EXCEPTION 'LDU-W scope cannot change (definition %)', OLD.id;
    END IF;
    IF NEW.scope_time_period IS DISTINCT FROM OLD.scope_time_period THEN
        RAISE EXCEPTION 'LDU-W scope cannot change (definition %)', OLD.id;
    END IF;
    
    -- Check if derivation_method changed (IMMUTABLE)
    IF NEW.derivation_method IS DISTINCT FROM OLD.derivation_method THEN
        RAISE EXCEPTION 'LDU-W derivation method is immutable (definition %)', OLD.id;
    END IF;
    
    -- Block ID changes (would break references)
    IF NEW.id IS DISTINCT FROM OLD.id THEN
        RAISE EXCEPTION 'LDU-W definition ID cannot be changed (definition %)', OLD.id;
    END IF;
    
    -- Block universe changes
    IF NEW.universe IS DISTINCT FROM OLD.universe THEN
        RAISE EXCEPTION 'LDU-W universe cannot be changed (definition %)', OLD.id;
    END IF;
    
    -- ALLOW changes to MUTABLE columns:
    -- - status (draft → reviewed → ready_for_promotion)
    -- - metadata (tags, notes, review feedback)
    -- - version (incremented on metadata/status changes)
    -- - updated_at (timestamp of last change)
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Attach trigger to ldu_w_definitions
DROP TRIGGER IF EXISTS ldu_w_immutability_trigger ON ldu_w_definitions;
CREATE TRIGGER ldu_w_immutability_trigger
