-- Phase 3 Milestone 0 Schema
-- Minimal storage for ObservabilityEvent ingestion

-- Audit Events (append-only ledger)
CREATE TABLE IF NOT EXISTS audit_events (
    rid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(255) NOT NULL,
    cid VARCHAR(64) NOT NULL,
    commit_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    payload_json JSONB NOT NULL,
    -- Denormalized columns for fast querying
    event_type VARCHAR(255),
    timestamp TIMESTAMPTZ,
    UNIQUE(tenant_id, cid)
);

-- Receipts (transaction outcomes, append-only)
CREATE TABLE IF NOT EXISTS receipts (
    rid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(255) NOT NULL,
    commit_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    outcome VARCHAR(20) NOT NULL CHECK (outcome IN ('FULL_ACCEPT', 'PARTIAL_ACCEPT', 'FULL_REJECT')),
    accepted_count INTEGER NOT NULL,
    rejected_count INTEGER NOT NULL,
    receipt_core_json JSONB NOT NULL,
    receipt_digest VARCHAR(64) NOT NULL,
    chain_hash VARCHAR(64) NOT NULL,
    previous_chain_hash VARCHAR(64),  -- Nullable for migration safety (Milestone 1)
    receipt_full_json JSONB
);

-- Chain State (per-tenant chain head, MUTABLE)
CREATE TABLE IF NOT EXISTS chain_state (
    tenant_id VARCHAR(255) PRIMARY KEY,
    current_chain_hash VARCHAR(64) NOT NULL,
    last_receipt_rid BIGINT NOT NULL REFERENCES receipts(rid),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes for common queries
CREATE INDEX IF NOT EXISTS idx_audit_events_tenant ON audit_events(tenant_id, commit_time DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_type ON audit_events(event_type);
CREATE INDEX IF NOT EXISTS idx_receipts_tenant ON receipts(tenant_id, commit_time DESC);

-- =============================================================================
-- PHASE 1: LDU-T (Raw Linguistic Data Universe)
-- Purpose: Store raw linguistic data WITHOUT semantic resolution
-- Key Constraint: resolution = null (enforced at schema level)
-- =============================================================================

-- LDU-T Entries (raw linguistic data, immutable content)
CREATE TABLE IF NOT EXISTS ldu_t_entries (
    id TEXT PRIMARY KEY,
    universe TEXT NOT NULL DEFAULT 'LDU-T' CHECK (universe = 'LDU-T'),
    source_type TEXT NOT NULL,
    source_metadata JSONB NOT NULL,          -- IMMUTABLE: original source info
    content JSONB NOT NULL,                  -- IMMUTABLE: raw text/transcription
    ambiguity_flags JSONB[] NOT NULL DEFAULT ARRAY[]::JSONB[],  -- IMMUTABLE: detected ambiguities
    resolution TEXT DEFAULT NULL CHECK (resolution IS NULL),     -- ENFORCED: must always be null
    provenance JSONB NOT NULL,               -- IMMUTABLE: ingestion record
    metadata JSONB DEFAULT '{}'::JSONB,      -- MUTABLE: tags, notes, review status (NOT source data)
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INT NOT NULL DEFAULT 1 CHECK (version > 0),
    tenant_id VARCHAR(255) NOT NULL DEFAULT 'default'
);

-- Metadata audit log (tracks non-destructive updates)
CREATE TABLE IF NOT EXISTS ldu_t_metadata_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ldu_t_id TEXT NOT NULL REFERENCES ldu_t_entries(id) ON DELETE CASCADE,
    old_metadata JSONB,
    new_metadata JSONB,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by TEXT NOT NULL
);

-- Ingestion receipts (detailed intake records)
CREATE TABLE IF NOT EXISTS ldu_t_ingestion_receipts (
    ingestion_id TEXT PRIMARY KEY,
    ingestion_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    ingestion_method TEXT NOT NULL,
    ingestion_actor TEXT NOT NULL,
    tenant_id VARCHAR(255) NOT NULL DEFAULT 'default',
    entries_submitted INT NOT NULL,
    entries_accepted INT NOT NULL,
    entries_rejected INT NOT NULL,
    rejected_details JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- LDU-T Indexes (for query performance)
CREATE INDEX IF NOT EXISTS idx_ldu_t_source_type ON ldu_t_entries(source_type);
CREATE INDEX IF NOT EXISTS idx_ldu_t_created_at ON ldu_t_entries(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ldu_t_universe ON ldu_t_entries(universe);
CREATE INDEX IF NOT EXISTS idx_ldu_t_source_metadata ON ldu_t_entries USING GIN(source_metadata);
CREATE INDEX IF NOT EXISTS idx_ldu_t_tenant ON ldu_t_entries(tenant_id);
CREATE INDEX IF NOT EXISTS idx_ldu_t_metadata_audit ON ldu_t_metadata_audit(ldu_t_id);
CREATE INDEX IF NOT EXISTS idx_ldu_t_ingestion_receipts ON ldu_t_ingestion_receipts(ingestion_timestamp DESC);

-- =============================================================================
-- IMMUTABILITY TRIGGERS: LDU-T content and provenance are append-only
-- =============================================================================

-- Prevent updates to critical columns (content, source, provenance, resolution)
-- ALLOWS updates to: metadata, version, updated_at (tracking/review fields)
CREATE OR REPLACE FUNCTION ldu_t_enforce_immutability()
RETURNS TRIGGER AS $$
BEGIN
    -- Block changes to IMMUTABLE columns (raw data)
    
    -- Check if content changed (IMMUTABLE)
    IF NEW.content IS DISTINCT FROM OLD.content THEN
        RAISE EXCEPTION 'LDU-T content is immutable (entry %)', OLD.id;
    END IF;
    
    -- Check if source_metadata changed (IMMUTABLE)
    IF NEW.source_metadata IS DISTINCT FROM OLD.source_metadata THEN
        RAISE EXCEPTION 'LDU-T source_metadata is immutable (entry %)', OLD.id;
    END IF;
    
    -- Check if provenance changed (IMMUTABLE)
    IF NEW.provenance IS DISTINCT FROM OLD.provenance THEN
        RAISE EXCEPTION 'LDU-T provenance is immutable (entry %)', OLD.id;
    END IF;
    
    -- Check if ambiguity_flags changed (IMMUTABLE)
    IF NEW.ambiguity_flags IS DISTINCT FROM OLD.ambiguity_flags THEN
        RAISE EXCEPTION 'LDU-T ambiguity_flags are immutable (entry %)', OLD.id;
    END IF;
    
    -- Resolution is protected by CHECK constraint, but enforce anyway
    IF NEW.resolution IS NOT NULL THEN
        RAISE EXCEPTION 'LDU-T resolution must always be null (entry %)', OLD.id;
    END IF;
    
    -- Block ID changes (would break references)
    IF NEW.id IS DISTINCT FROM OLD.id THEN
        RAISE EXCEPTION 'LDU-T entry ID cannot be changed (entry %)', OLD.id;
    END IF;
    
    -- Block universe changes (would violate layer separation)
    IF NEW.universe IS DISTINCT FROM OLD.universe THEN
        RAISE EXCEPTION 'LDU-T universe cannot be changed (entry %)', OLD.id;
    END IF;
    
    -- ALLOW changes to MUTABLE columns:
    -- - metadata (tags, notes, review status)
    -- - version (auto-incremented on metadata updates)
    -- - updated_at (timestamp of last change)
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Attach trigger to ldu_t_entries
DROP TRIGGER IF EXISTS ldu_t_immutability_trigger ON ldu_t_entries;
CREATE TRIGGER ldu_t_immutability_trigger
BEFORE UPDATE ON ldu_t_entries
FOR EACH ROW
EXECUTE FUNCTION ldu_t_enforce_immutability();
-- =============================================================================
-- PHASE 2: LDU-W (LOCAL WORKABLE DEFINITION UNIVERSE)
-- =============================================================================

-- Workable definitions (derived from LDU-T, immutable once written)
CREATE TABLE IF NOT EXISTS ldu_w_definitions (
    id TEXT PRIMARY KEY,
    universe TEXT NOT NULL DEFAULT 'LDU-W',
    term TEXT NOT NULL,
    
    -- Workable claim (the actual definition/interpretation)
    claim JSONB NOT NULL,
    
    -- Lineage: which LDU-T entries does this derive from?
    source_ldu_t_ids TEXT[] NOT NULL,
    
    -- GDU shape declaration (what structure does this target?)
    gdu_shape JSONB NOT NULL,
    
    -- Explicit scope (all required, non-null)
    scope_domain TEXT NOT NULL,
    scope_culture TEXT NOT NULL,
    scope_community TEXT NOT NULL,
    scope_time_period TEXT NOT NULL,
    
    -- How was this definition derived?
    derivation_method TEXT NOT NULL,
    
    -- Status tracking (mutable)
    status TEXT DEFAULT 'draft' CHECK (status IN ('draft', 'reviewed', 'ready_for_promotion')),
    
    -- Mutable metadata (tags, notes, review feedback)
    metadata JSONB DEFAULT '{}',
    
    -- Version tracking (incremented on metadata/status changes)
    version INT DEFAULT 1,
    
    -- Audit timestamps
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    
    -- Multi-tenancy
    tenant_id TEXT NOT NULL,
    
    -- Constraints
    CONSTRAINT ldu_w_source_not_empty CHECK (array_length(source_ldu_t_ids, 1) > 0),
    CONSTRAINT ldu_w_term_format CHECK (term ~ '^[a-z0-9_]+$'),
    CONSTRAINT ldu_w_scope_normalized CHECK (
        scope_domain != '' AND scope_culture != '' AND scope_community != '' AND scope_time_period != ''
    )
);

-- Ingestion receipt log (like LDU-T)
CREATE TABLE IF NOT EXISTS ldu_w_ingestion_receipts (
    ingestion_id TEXT PRIMARY KEY,
    ingestion_timestamp TIMESTAMP NOT NULL,
    ingestion_method TEXT NOT NULL,
    ingestion_actor TEXT NOT NULL,
    definitions_submitted INT NOT NULL,
    definitions_accepted INT NOT NULL,
    definitions_rejected INT NOT NULL,
    rejected_details JSONB,
    tenant_id TEXT NOT NULL
);

-- Metadata audit trail (optional, for tracking metadata/status changes)
CREATE TABLE IF NOT EXISTS ldu_w_metadata_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    definition_id TEXT NOT NULL REFERENCES ldu_w_definitions(id) ON DELETE CASCADE,
    old_metadata JSONB,
    new_metadata JSONB,
    old_status TEXT,
    new_status TEXT,
    changed_by TEXT NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT NOW(),
    tenant_id TEXT NOT NULL
);

-- =============================================================================
-- INDEXES FOR LDU-W
